FEATURED_EVENT_INDEXES = (0, 6, 12, 18, 24, 30)



def js_round(x: float) -> int:
    """JavaScript Math.round (half rounds toward +infinity)."""
    return math.floor(x + 0.5)


def track_for(category: str, geo: str) -> str:
    return f"{category} · {geo.replace('→', ' / ', 1)}"


def ai_allowed_for(category: str, index: int) -> bool:
    return category not in ("红色情怀", "康养生活", "公益") and index % 7 != 0


def video_status_for(title: str, index: int) -> str:
    if title == "银龄才艺开放麦":
        return "已接入测试 · 待验证"
    return "支持视频号链接" if index % 4 == 0 else "待提交视频号"


def cover_for(title: str, index: int) -> str:
    return THEME_SCENE_FILES.get(title) or f"event-cover-{index + 1:02d}.webp"


def build_event(index: int) -> dict:
    title, category, desc, geo, status_text, emoji, flower_count = EVENT_ROWS[index]
    participant_count = max(36, js_round(flower_count * 0.62 + 24 + (index % 6) * 17))
    heat = min(99, max(58, js_round(64 + flower_count / 42 + (index % 9))))
    ai_allowed = ai_allowed_for(category, index)
    return {
        "title": title,
        "category": category,
        "desc": desc,
        "geo": geo,
        "status_text": status_text,
        "emoji": emoji,
        "icon_key": CATEGORY_ICON_KEYS[category],
        "cover": cover_for(title, index),
        "heat": heat,
        "participant_count": participant_count,
        "flower_count": flower_count,
        "reward_text": CATEGORY_REWARDS[category],
        "ai_allowed": ai_allowed,
        "ai_label": "AI辅助可选" if ai_allowed else "原声/实拍优先",
        "track": track_for(category, geo),
        "video_status": video_status_for(title, index),
        "featured": index in FEATURED_EVENT_INDEXES,
        "sort_order": index,
    }


def build_events() -> list[dict]:
    return [build_event(i) for i in range(len(EVENT_ROWS))]


