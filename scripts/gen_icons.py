COLORS = {
    "olive": "#4b582c",
    "muted": "#9a8976",
    "orange": "#d97945",
    "cream": "#fffaf2",
}


def svg(path: str, color: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">{path}</svg>'
    )


def main() -> None:
    icons = {}
    for name, path in PATHS.items():
        icons[name] = {
            key: "data:image/svg+xml;base64," + base64.b64encode(svg(path, color).encode()).decode()
            for key, color in COLORS.items()
        }
    body = json.dumps(icons, ensure_ascii=False, indent=0, separators=(",", ":"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/gen_icons.py — do not edit by hand.\n"
        "// icons[name][color] => data URI; colors: olive | muted | orange | cream\n"
        f"module.exports = {body}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(icons)} icons)")


if __name__ == "__main__":
    main()
